from aiogram.fsm.state import State, StatesGroup


class ReportFlow(StatesGroup):
    """Состояния, в которых следующий текст — не новый отчёт, а ответ на вопрос бота.

    Всё остальное (карточка, варианты) живёт в черновике в базе и от состояния не зависит,
    поэтому после перезапуска бота кнопки продолжают работать.
    """

    editing_qty = State()  # ждём число: объём позиции (ответ на вопрос или правка)
    adding = State()  # ждём ещё позиции текстом («Добавить»)
    correcting_today = State()  # ждём число: новый объём уже записанной сегодня строки
